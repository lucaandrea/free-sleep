import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const tokens = JSON.parse(await readFile(path.join(root, 'design/tokens.json'), 'utf8'));
const files = new Map();
const typescript = JSON.stringify(tokens, null, 2).replace(/"([A-Za-z][A-Za-z0-9]*)":/g, '$1:').replace(/"(#[a-f0-9]{6})"/gi, "'$1'");
files.set('app/src/design/tokens.ts', `// Generated by scripts/generate-design.mjs. Edit design/tokens.json.\nexport const design = ${typescript} as const;\n`);
const declarations = Object.entries({ layout: tokens.layout, type: tokens.type }).map(([group, values]) =>
  `    enum ${group === 'layout' ? 'Layout' : 'Typography'} {\n${Object.entries(values).map(([key, value]) => `        static let ${key}: CGFloat = ${value}`).join('\n')}\n    }`);
files.set('ios/FreeSleep/Design/SleepTokens.swift', `// Generated by scripts/generate-design.mjs. Edit design/tokens.json.\nimport SwiftUI\n\nenum SleepTokens {\n${declarations.join('\n')}\n}\n`);

// Asset colors resolve through SwiftUI's color scheme without a UIKit dependency.
for (const [name, modes] of Object.entries(tokens.colors)) {
  const colors = Object.entries(modes).map(([mode, hex]) => {
    if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`Invalid ${name} ${mode} color`);
    const components = Object.fromEntries(['red', 'green', 'blue'].map((channel, index) =>
      [channel, (parseInt(hex.slice(1 + index * 2, 3 + index * 2), 16) / 255).toFixed(6)]));
    return { idiom: 'universal', ...(mode === 'dark' ? { appearances: [{ appearance: 'luminosity', value: 'dark' }] } : {}),
      color: { 'color-space': 'srgb', components: { ...components, alpha: '1.000000' } } };
  });
  files.set(`ios/FreeSleep/Resources/Assets.xcassets/Sleep${name[0].toUpperCase()}${name.slice(1)}.colorset/Contents.json`,
    `${JSON.stringify({ colors, info: { author: 'xcode', version: 1 } }, null, 2)}\n`);
}
const check = process.argv.includes('--check');
let stale = false;
for (const [relative, content] of files) {
  const target = path.join(root, relative);
  if (check) {
    if (await readFile(target, 'utf8').catch(() => '') !== content) { process.stderr.write(`Design output needs generation: ${relative}\n`); stale = true; }
  } else { await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, content); }
}
if (stale) process.exitCode = 1;
else process.stdout.write(`${check ? 'Verified' : 'Generated'} ${files.size} shared design outputs.\n`);
